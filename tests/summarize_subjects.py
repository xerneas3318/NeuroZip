"""Summarize tests/results/{SUBJECTS,LOSO}.json into tests/results/SUBJECTS.md.

For each tier x view: mean +/- SD across subjects of image top-5 retrieval
for fidelity and NeuroZip, the paired per-subject delta (NeuroZip - fidelity),
how many subjects improved, and paired t / Wilcoxon p-values across subjects.

Run:  .venv/bin/python tests/summarize_subjects.py
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np
from scipy import stats

R = Path(__file__).resolve().parent / "results"
VIEWS = ("avg80", "avg4", "single")


def ms(a, scale=100):
    a = np.asarray(a) * scale
    return f"{a.mean():.1f} ± {a.std(ddof=1) if len(a) > 1 else 0:.1f}"


def section(title, runs, gallery="image", k="top5"):
    subs = sorted(runs)
    lines = [f"## {title}", "", f"{len(subs)} subjects: {', '.join(subs)}. "
             f"Metric: {gallery} {k} retrieval (%), 200-way, chance {500/200 if k=='top5' else 0.5:.1f}%.", ""]
    # ceiling
    lines += ["**Uncompressed ceiling (judge on raw EEG)**", "",
              "| view | " + " | ".join(VIEWS) + " |", "|---|" + "---|" * len(VIEWS),
              "| raw | " + " | ".join(ms([runs[s]["ceiling_raw"][v][gallery][k] for s in subs])
                                    for v in VIEWS) + " |", ""]
    tiers = list(runs[subs[0]]["tiers"])
    lines += ["**Fidelity vs NeuroZip (same arch, init, steps)**", "",
              "| tier | view | bpp fid | bpp NZ | MSE fid | MSE NZ | fidelity | NeuroZip | Δ (NZ−fid) | NZ wins | p (t) | p (Wilcoxon) |",
              "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for t in tiers:
        for v in VIEWS:
            f = np.array([runs[s]["tiers"][t]["fidelity"][v]["retrieval"][gallery][k] for s in subs])
            z = np.array([runs[s]["tiers"][t]["neurozip"][v]["retrieval"][gallery][k] for s in subs])
            bf = np.mean([runs[s]["tiers"][t]["fidelity"]["bpp"] for s in subs])
            bz = np.mean([runs[s]["tiers"][t]["neurozip"]["bpp"] for s in subs])
            mf = np.mean([runs[s]["tiers"][t]["fidelity"][v]["mse"] for s in subs])
            mz = np.mean([runs[s]["tiers"][t]["neurozip"][v]["mse"] for s in subs])
            dlt = z - f
            if len(subs) > 1 and np.any(dlt != 0):
                pt = stats.ttest_rel(z, f).pvalue
                pw = stats.wilcoxon(z, f).pvalue
                ps = f"{pt:.2g}", f"{pw:.2g}"
            else:
                ps = "–", "–"
            lines.append(f"| {t} | {v} | {bf:.3f} | {bz:.3f} | {mf:.3f} | {mz:.3f} | {ms(f)} | {ms(z)} | "
                         f"{ms(dlt)} | {int((dlt > 0).sum())}/{len(subs)} | {ps[0]} | {ps[1]} |")
    lines.append("")
    # matched bitrate: interpolate each subject's fidelity RD curve at NZ's bpp
    lines += ["**Matched bitrate** — each subject's fidelity curve (3 tiers) linearly interpolated "
              "in log-bpp at NeuroZip's actual bpp (clamped to the fidelity range):", "",
              "| tier | view | NZ bpp | fidelity @ NZ bpp | NeuroZip | Δ | NZ wins | p (t) | p (Wilcoxon) |",
              "|---|---|---|---|---|---|---|---|---|"]
    for t in tiers:
        for v in VIEWS:
            fi, zz, bz = [], [], []
            for s in subs:
                pts = sorted((runs[s]["tiers"][u]["fidelity"]["bpp"],
                              runs[s]["tiers"][u]["fidelity"][v]["retrieval"][gallery][k]) for u in tiers)
                b = runs[s]["tiers"][t]["neurozip"]["bpp"]
                fi.append(float(np.interp(np.log(b), np.log([q[0] for q in pts]), [q[1] for q in pts])))
                zz.append(runs[s]["tiers"][t]["neurozip"][v]["retrieval"][gallery][k]); bz.append(b)
            fi, zz = np.array(fi), np.array(zz); dlt = zz - fi
            ok = len(subs) > 1 and np.any(dlt != 0)
            pt = f"{stats.ttest_rel(zz, fi).pvalue:.2g}" if ok else "–"
            pw = f"{stats.wilcoxon(zz, fi).pvalue:.2g}" if ok else "–"
            lines.append(f"| {t} | {v} | {np.mean(bz):.3f} | {ms(fi)} | {ms(zz)} | {ms(dlt)} | "
                         f"{int((dlt > 0).sum())}/{len(subs)} | {pt} | {pw} |")
    lines.append("")
    # per-subject single-trial detail
    lines += [f"**Per-subject {gallery} {k} (%), single-trial view**", "",
              "| subject | raw | " + " | ".join(f"{t} fid | {t} NZ" for t in tiers) + " |",
              "|---|---|" + "---|---|" * len(tiers)]
    for s in subs:
        r = runs[s]
        row = [f"{100*r['ceiling_raw']['single'][gallery][k]:.1f}"]
        for t in tiers:
            row += [f"{100*r['tiers'][t][m]['single']['retrieval'][gallery][k]:.1f}"
                    for m in ("fidelity", "neurozip")]
        lines.append(f"| {s} | " + " | ".join(row) + " |")
    lines.append("")
    return lines


def main():
    out = ["# Multi-subject and cross-subject results (grant workstream 1)", "",
           "Generated by `tests/summarize_subjects.py` from `SUBJECTS.json` / `LOSO.json`.",
           "Harnesses: `tests/exp_subjects.py` (within-subject), `tests/exp_loso.py` (leave-one-subject-out).",
           "Views: **avg80** = 80 repetitions averaged (paper protocol, 200 queries); "
           "**avg4** = disjoint 4-rep averages (4,000 queries); **single** = every single trial (16,000 queries).",
           "bpp is the modeled rate (bits per EEG sample) on avg80; fp16 = 16 bpp.", ""]
    for name, key, title in (("SUBJECTS.json", "subjects", "Within-subject (each subject trains its own judge + codecs)"),
                             ("SUBJECTS_seed1.json", "subjects", "Within-subject replicate, seed 1"),
                             ("LOSO.json", "folds", "Leave-one-subject-out (train on 9, test on held-out)")):
        p = R / name
        if p.exists():
            runs = json.loads(p.read_text()).get(key, {})
            if runs:
                cfg = json.loads(p.read_text())["config"]
                out += section(title, runs)
                out += [f"Config: `{json.dumps(cfg)}`", ""]
                if len(runs) > 0:
                    out += section(title + " — text gallery", runs, gallery="text")[2:]
    (R / "SUBJECTS.md").write_text("\n".join(out))
    print("\n".join(out))


if __name__ == "__main__":
    main()
